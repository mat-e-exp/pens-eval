/**
 * Bitbucket Pipelines Templates
 *
 * Generates bitbucket-pipelines.yml from an EnforcementPlan.
 * Bitbucket has no native path filtering — path scoping done via
 * git diff conditionals in step scripts.
 */

'use strict';

const { consolidateJobs } = require('../platform-adapter');

/**
 * @param {EnforcementPlan} plan
 * @returns {FileOutput[]}
 */
function generateBitbucketConfig(plan) {
  const securityJobs = consolidateJobs(plan.ciOnPush.jobs.filter(j =>
    ['trivy-secrets', 'trivy-cve', 'semgrep', 'codeql', 'dangerous-config', 'suppression', 'lockfile'].includes(j.tool) ||
    j.id.startsWith('security-')
  ));

  const qualityJobs = consolidateJobs(plan.ciOnPush.jobs.filter(j =>
    j.tool === 'lint' || j.tool === 'licence'
  ));

  const securitySteps = securityJobs.map(job => {
    const scopeCheck = job.scope !== '**/*'
      ? `          # Path-scoped: only run if matching files changed\n          - FILES=$(git diff --name-only origin/main...HEAD -- '${job.scope}'); if [ -z "$FILES" ]; then echo "No matching files changed, skipping"; exit 0; fi\n`
      : '';

    return `        - step:
            name: ${job.name}
            script:
${scopeCheck}              - ${jobRunLine(job)}`;
  }).join('\n');

  const qualitySteps = qualityJobs.map(job => {
    return `        - step:
            name: ${job.name}
            script:
              - ${jobRunLine(job)}`;
  }).join('\n');

  const locMax = plan.prGate.checks.find(c => c.type === 'loc_limit')?.config.max || 400;

  const content = `# Generated by devflow — do not edit manually
image: ubuntu:latest

pipelines:
  default:
    - parallel:
${securitySteps}
    - parallel:
${qualitySteps}

  pull-requests:
    '**':
      - step:
          name: PR size check
          script:
            - TOTAL=$(git diff --stat origin/main...HEAD | tail -1 | grep -oP '\\d+(?= insertion)' || echo 0)
            - |
              if [ "$TOTAL" -gt "${locMax}" ]; then
                echo "PR exceeds ${locMax} LOC limit ($TOTAL lines changed)"
                exit 1
              fi
      - parallel:
${securitySteps}

  custom:
    devflow-audit:
      - step:
          name: Append audit log
          script:
            - mkdir -p .devflow
            - echo '{"timestamp":"'$(date -u +%Y-%m-%dT%H:%M:%SZ)'","result":"passed","repo":"$BITBUCKET_REPO_FULL_NAME","branch":"$BITBUCKET_BRANCH","commit":"$BITBUCKET_COMMIT"}' > .devflow/audit-entry.json
          artifacts:
            - .devflow/audit-entry.json
`;

  return [{
    path: 'bitbucket-pipelines.yml',
    content,
    overwrite: true,
  }];
}

/**
 * The shell line a CI job runs. A job may set `ciRun` when the plain
 * `command args` form cannot express what it needs — for example scanning an
 * explicit file list rather than a directory (DEC-028).
 */
function jobRunLine(job) {
  return job.ciRun || `${job.command} ${job.args.join(' ')}`;
}

module.exports = { generateBitbucketConfig };
