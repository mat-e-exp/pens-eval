/**
 * GitHub Actions Workflow Templates
 *
 * JS functions that return YAML strings. No template engine.
 * Each function generates one workflow file.
 */

'use strict';

const { consolidateJobs } = require('../platform-adapter');

/**
 * Generate all workflow files from an enforcement plan.
 *
 * @param {EnforcementPlan} plan
 * @returns {FileOutput[]}
 */
function generateWorkflows(plan) {
  const files = [];

  files.push({
    path: '.github/workflows/devflow-security.yml',
    content: generateSecurityWorkflow(plan),
    overwrite: true,
  });

  files.push({
    path: '.github/workflows/devflow-quality.yml',
    content: generateQualityWorkflow(plan),
    overwrite: true,
  });

  files.push({
    path: '.github/workflows/devflow-pr-gate.yml',
    content: generatePRGateWorkflow(plan),
    overwrite: true,
  });

  files.push({
    path: '.github/workflows/devflow-audit.yml',
    content: generateAuditWorkflow(plan),
    overwrite: true,
  });

  return files;
}

function generateSecurityWorkflow(plan) {
  const securityJobs = deduplicateJobs(plan.ciOnPush.jobs.filter(j =>
    ['trivy-secrets', 'trivy-cve', 'semgrep', 'codeql', 'dangerous-config', 'suppression', 'lockfile'].includes(j.tool) ||
    j.id.startsWith('security-')
  ));

  const consolidated = consolidateJobs(securityJobs);

  const jobs = consolidated.map(job => {
    const continueOnError = plan.failPolicy[job.tool] !== 'closed';

    // CodeQL is a GitHub Action, not a CLI command
    if (job.isGitHubAction && job.tool === 'codeql') {
      return `  ${sanitiseJobId(job.id)}:
    name: ${job.name}
    runs-on: ubuntu-latest${continueOnError ? '\n    continue-on-error: true' : ''}
    steps:
      - uses: actions/checkout@v4
      - name: Initialize CodeQL
        uses: github/codeql-action/init@v3
      - name: Autobuild
        uses: github/codeql-action/autobuild@v3
      - name: Perform CodeQL Analysis
        uses: github/codeql-action/analyze@v3${buildNotifyStep(job, plan)}`;
    }

    const setup = buildSetupSteps(job);
    return `  ${sanitiseJobId(job.id)}:
    name: ${job.name}
    runs-on: ubuntu-latest${continueOnError ? '\n    continue-on-error: true' : ''}
    steps:
      - uses: actions/checkout@v4${buildCheckoutWith(job)}
${setup ? setup + '\n' : ''}      - name: Run ${job.name}
        run: ${jobRunLine(job)}${buildNotifyStep(job, plan)}`;
  }).join('\n\n');

  return `# Generated by devflow — do not edit manually
name: devflow Security

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

permissions:
  contents: read

jobs:
${jobs}
`;
}

function generateQualityWorkflow(plan) {
  const qualityJobs = deduplicateJobs(plan.ciOnPush.jobs.filter(j =>
    j.tool === 'lint' || j.tool === 'licence'
  ));

  const consolidated = consolidateJobs(qualityJobs);

  const jobs = consolidated.map(job => {
    const continueOnError = plan.failPolicy[job.tool] !== 'closed';
    const pathsFilter = job.scope !== '**/*' ? buildOnPathsYaml(job.scope) : '';

    const setup = buildSetupSteps(job);
    return `  ${sanitiseJobId(job.id)}:
    name: ${job.name}
    runs-on: ubuntu-latest${continueOnError ? '\n    continue-on-error: true' : ''}
    steps:
      - uses: actions/checkout@v4
${setup ? setup + '\n' : ''}      - name: Run ${job.name}
        run: ${jobRunLine(job)}`;
  }).join('\n\n');

  return `# Generated by devflow — do not edit manually
name: devflow Quality

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

permissions:
  contents: read

jobs:
${jobs}
`;
}

function generatePRGateWorkflow(plan) {
  const checks = plan.prGate.checks;
  const locCheck = checks.find(c => c.type === 'loc_limit');
  const branchCheck = checks.find(c => c.type === 'branch_naming');

  return `# Generated by devflow — do not edit manually
name: devflow PR Gate

on:
  pull_request:
    branches: [main]
    types: [opened, synchronize, reopened]

permissions:
  contents: read
  pull-requests: read

jobs:
  pr-size:
    name: PR size check
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - name: Check PR size
        run: |
          LINES=$(git diff --stat origin/main...HEAD | tail -1 | grep -oP '\\d+(?= insertion)' || echo 0)
          DELETIONS=$(git diff --stat origin/main...HEAD | tail -1 | grep -oP '\\d+(?= deletion)' || echo 0)
          TOTAL=$((LINES + DELETIONS))
          MAX=${locCheck ? locCheck.config.max : 400}
          if [ "$TOTAL" -gt "$MAX" ]; then
            echo "::error::PR exceeds ${locCheck ? locCheck.config.max : 400} LOC limit ($TOTAL lines changed)"
            exit 1
          fi
          echo "PR size: $TOTAL lines (limit: $MAX)"

  branch-naming:
    name: Branch naming convention
    runs-on: ubuntu-latest
    steps:
      - name: Check branch name
        env:
          BRANCH: \${{ github.head_ref }}
        run: |
          if [[ ! "$BRANCH" =~ ^(${branchCheck ? branchCheck.config.prefixes.join('|').replace(/\//g, '\\/') : 'feature\\/|hotfix\\/|deps\\/|experiment\\/'}). ]]; then
            echo "::error::Branch name '$BRANCH' does not match required prefixes"
            exit 1
          fi
          echo "Branch name '$BRANCH' is valid"
`;
}

function generateAuditWorkflow(plan) {
  return `# Generated by devflow — do not edit manually
name: devflow Audit

on:
  workflow_run:
    workflows: ["devflow Security", "devflow Quality", "devflow PR Gate"]
    types: [completed]

permissions:
  contents: read

jobs:
  audit-log:
    name: Append audit log
    runs-on: ubuntu-latest
    steps:
      - name: Write audit entry
        run: |
          mkdir -p .devflow
          echo '{"timestamp":"'$(date -u +%Y-%m-%dT%H:%M:%SZ)'","workflow":"\${{ github.event.workflow_run.name }}","result":"\${{ github.event.workflow_run.conclusion }}","repo":"\${{ github.repository }}","branch":"\${{ github.event.workflow_run.head_branch }}","commit":"\${{ github.event.workflow_run.head_sha }}"}' > .devflow/audit-entry.json
      - name: Upload audit entry
        uses: actions/upload-artifact@v4
        with:
          name: audit-log-\${{ github.event.workflow_run.id }}
          path: .devflow/audit-entry.json
          retention-days: 90
`;
}

/**
 * Build a notification step for Discord/email when a job fails.
 */
function buildNotifyStep(job, plan) {
  if (!plan.notifications.discord || plan.failPolicy[job.tool] === 'open') {
    return '';
  }

  return `
      - name: Notify on failure
        if: failure()
        run: |
          curl -s -X POST "\${{ secrets.DISCORD_WEBHOOK }}" \\
            -H "Content-Type: application/json" \\
            -d '{"content":"⚠️ **${job.name}** failed on \`\${{ github.ref_name }}\` — \${{ github.server_url }}/\${{ github.repository }}/actions/runs/\${{ github.run_id }}"}'`;
}

function deduplicateJobs(jobs) {
  const seen = new Set();
  return jobs.filter(job => {
    const id = sanitiseJobId(job.id);
    if (seen.has(id)) return false;
    seen.add(id);
    return true;
  });
}

function sanitiseJobId(id) {
  return id.replace(/[^a-zA-Z0-9-]/g, '-').replace(/-+/g, '-');
}

/**
 * Generate setup steps to install a tool on the CI runner.
 * Returns YAML string for the steps, or empty string if no setup needed.
 */
function buildSetupSteps(job) {
  const tool = job.command;
  if (!tool) return '';

  const SETUP = {
    trivy: `      - name: Install Trivy
        run: |
          sudo apt-get install -y wget apt-transport-https gnupg lsb-release
          wget -qO - https://aquasecurity.github.io/trivy-repo/deb/public.key | gpg --dearmor | sudo tee /usr/share/keyrings/trivy.gpg > /dev/null
          echo "deb [signed-by=/usr/share/keyrings/trivy.gpg] https://aquasecurity.github.io/trivy-repo/deb generic main" | sudo tee /etc/apt/sources.list.d/trivy.list
          sudo apt-get update && sudo apt-get install -y trivy`,
    semgrep: `      - name: Install Semgrep
        run: pip install semgrep`,
    ruff: `      - name: Install Ruff
        run: pip install ruff`,
    black: `      - name: Install Black
        run: pip install black`,
    bandit: `      - name: Install Bandit
        run: pip install bandit`,
    eslint: `      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '18'
      - name: Install ESLint
        run: npm install -g eslint`,
    prettier: `      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '18'
      - name: Install Prettier
        run: npm install -g prettier`,
    'pip-audit': `      - name: Install pip-audit
        run: pip install pip-audit`,
    'pip-licenses': `      - name: Install pip-licenses
        run: pip install pip-licenses`,
    npm: `      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '18'`,
    npx: `      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '18'`,
  };

  return SETUP[tool] || '';
}

function buildPathFilter(scope) {
  if (scope === '**/*') return null;
  return scope;
}

function buildOnPathsYaml(scope) {
  if (!scope || scope === '**/*') return '';
  return `    paths:\n      - '${scope}'`;
}

/**
 * The shell line a CI job runs. A job may set `ciRun` when the plain
 * `command args` form cannot express what it needs — for example scanning an
 * explicit file list rather than a directory (DEC-028).
 */
/**
 * A gate that scans a commit range needs the history to compare against;
 * the default shallow checkout has only one commit.
 */
function buildCheckoutWith(job) {
  return job.needsFullHistory ? `
        with:
          fetch-depth: 0` : '';
}

function jobRunLine(job) {
  return job.ciRun || `${job.command} ${job.args.join(' ')}`;
}

module.exports = { generateWorkflows };
