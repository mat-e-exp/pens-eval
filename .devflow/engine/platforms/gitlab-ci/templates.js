/**
 * GitLab CI Templates
 *
 * Generates a single .gitlab-ci.yml from an EnforcementPlan.
 * GitLab uses one config file with stages, unlike GitHub's multi-file approach.
 */

'use strict';

const { consolidateJobs } = require('../platform-adapter');

/**
 * @param {EnforcementPlan} plan
 * @returns {FileOutput[]}
 */
function generateGitLabConfig(plan) {
  const securityJobs = consolidateJobs(plan.ciOnPush.jobs.filter(j =>
    ['trivy-secrets', 'trivy-cve', 'semgrep', 'codeql', 'dangerous-config', 'suppression', 'lockfile'].includes(j.tool) ||
    j.id.startsWith('security-')
  ));

  const qualityJobs = consolidateJobs(plan.ciOnPush.jobs.filter(j =>
    j.tool === 'lint' || j.tool === 'licence'
  ));

  const securitySection = securityJobs.map(job => {
    const allowFailure = plan.failPolicy[job.tool] !== 'closed';
    const changes = job.scope !== '**/*' ? `\n  rules:\n    - changes:\n        - "${job.scope}"` : '';

    return `${sanitiseJobId(job.id)}:
  stage: security
  image: ubuntu:latest${allowFailure ? '\n  allow_failure: true' : ''}
  script:
    - ${jobRunLine(job)}${changes}`;
  }).join('\n\n');

  const qualitySection = qualityJobs.map(job => {
    const allowFailure = plan.failPolicy[job.tool] !== 'closed';

    return `${sanitiseJobId(job.id)}:
  stage: quality
  image: ubuntu:latest${allowFailure ? '\n  allow_failure: true' : ''}
  script:
    - ${jobRunLine(job)}`;
  }).join('\n\n');

  const content = `# Generated by devflow — do not edit manually
stages:
  - security
  - quality
  - gate
  - audit

${securitySection}

${qualitySection}

pr-size-check:
  stage: gate
  script:
    - |
      TOTAL=$(git diff --stat origin/main...HEAD | tail -1 | grep -oP '\\d+(?= insertion)' || echo 0)
      MAX=${plan.prGate.checks.find(c => c.type === 'loc_limit')?.config.max || 400}
      if [ "$TOTAL" -gt "$MAX" ]; then
        echo "MR exceeds $MAX LOC limit ($TOTAL lines changed)"
        exit 1
      fi
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"

audit-log:
  stage: audit
  script:
    - mkdir -p .devflow
    - echo '{"timestamp":"'$(date -u +%Y-%m-%dT%H:%M:%SZ)'","result":"$CI_JOB_STATUS","repo":"$CI_PROJECT_PATH","branch":"$CI_COMMIT_REF_NAME","commit":"$CI_COMMIT_SHA"}' >> ${plan.audit.logPath}
  when: always
`;

  return [{
    path: '.gitlab-ci.yml',
    content,
    overwrite: true,
  }];
}

function sanitiseJobId(id) {
  return id.replace(/[^a-zA-Z0-9-]/g, '-').replace(/-+/g, '-');
}

/**
 * The shell line a CI job runs. A job may set `ciRun` when the plain
 * `command args` form cannot express what it needs — for example scanning an
 * explicit file list rather than a directory (DEC-028).
 */
function jobRunLine(job) {
  return job.ciRun || `${job.command} ${job.args.join(' ')}`;
}

module.exports = { generateGitLabConfig };
