/**
 * Agent Instructions
 *
 * Writes the repo's enforcement rules into the instruction file(s) that
 * AI coding agents read on every task — CLAUDE.md, AGENTS.md — so the
 * agent avoids the gate instead of hitting it.
 *
 * Content is derived from the enforcement plan, so it is per-repo accurate:
 * which hooks run at pre-commit and with what fail policy, what runs on
 * push and in CI, which suppression tokens are blocked for the detected
 * languages, PR size and branch rules.
 *
 * The rules live in a managed block delimited by BEGIN_MARK / END_MARK.
 * Anything outside the block is left untouched; the block itself is
 * replaced in full on every `devflow init` / `devflow update`.
 *
 * Config (.devflow/config.yml):
 *   agentInstructions: false                   # disable entirely
 *   agentInstructionFiles: [CLAUDE.md, AGENTS.md]   # targets (default shown)
 *
 * Behaviour: every listed file that already exists gets the block. If none
 * exist, all listed files are created containing only the block.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { PATTERNS } = require('./suppression-scanner');

const BEGIN_MARK = '<!-- devflow:begin -->';
const END_MARK = '<!-- devflow:end -->';
const DEFAULT_FILES = ['CLAUDE.md', 'AGENTS.md'];

/** Representative file extension per detected language, for pattern selection. */
const LANGUAGE_EXT = {
  javascript: 'js',
  typescript: 'ts',
  python: 'py',
  go: 'go',
  java: 'java',
  rust: 'rs',
  ruby: 'rb',
  terraform: 'tf',
};

/** Human-readable token per suppression pattern id. */
const PATTERN_TOKEN = {
  'eslint-disable': 'eslint-disable',
  'noqa': '# noqa',
  'pylint-disable': '# pylint: disable',
  'nolint': '//nolint',
  'rubocop-disable': '# rubocop:disable',
  'rust-allow': '#[allow(...)]',
  'suppress-warnings': '@SuppressWarnings',
  'ts-ignore': '@ts-ignore',
  'ts-nocheck': '@ts-nocheck',
  'type-ignore': '# type: ignore',
  'nosec': '# nosec',
  'nosemgrep': 'nosemgrep',
  'tfsec-ignore': '# tfsec:ignore',
  'trivy-ignore': '# trivy:ignore',
  'checkov-skip': '# checkov:skip',
  'tflint-ignore': '# tflint-ignore',
  'no-cover': '# pragma: no cover',
  'coverage-ignore': '/* istanbul|c8|v8 ignore */',
  'test-only': '.only(',
  'test-skip': '.skip( / xit / xdescribe',
  'pytest-skip': '@pytest.mark.skip / skipif / xfail',
  'go-skip': 't.Skip(',
  'rust-ignore': '#[ignore]',
};

const POLICY_LABEL = {
  closed: 'blocks',
  open: 'warns',
  'open-notify': 'warns',
};

function policyLabel(policy) {
  return POLICY_LABEL[policy] || 'warns';
}

/**
 * Resolve config into targets and enabled flag.
 */
function resolveOptions(config = {}) {
  const enabled = config.agentInstructions !== false;
  const files = Array.isArray(config.agentInstructionFiles) && config.agentInstructionFiles.length > 0
    ? config.agentInstructionFiles.map(String)
    : DEFAULT_FILES;
  return { enabled, files };
}

/**
 * Suppression patterns that apply to the plan's detected languages,
 * minus anything the repo has allowed via suppressionAllow.
 */
function blockedPatterns(plan, config = {}) {
  const allow = new Set(Array.isArray(config.suppressionAllow) ? config.suppressionAllow : []);
  const exts = new Set(
    (plan.stacks || []).map(s => LANGUAGE_EXT[s.language]).filter(Boolean)
  );
  if (exts.size === 0) return [];
  return PATTERNS.filter(p => !allow.has(p.id) && p.extensions.some(e => exts.has(e)));
}

/**
 * Build the managed markdown block from an enforcement plan.
 *
 * @param {Object} plan - Enforcement plan (from orchestrator.init / loadPlan)
 * @param {Object} [config] - Parsed .devflow/config.yml
 * @returns {string} Markdown, including begin/end markers
 */
function buildAgentInstructions(plan, config = {}) {
  const lines = [];
  const preCommit = (plan.preCommit && plan.preCommit.hooks) || [];
  const ciJobs = (plan.ciOnPush && plan.ciOnPush.jobs) || [];
  const testJobs = ciJobs.filter(j => j.tool === 'test' && j.command);
  const testing = config.testing || {};
  const prePushEnabled = testJobs.length > 0 && testing.prePush !== false;
  const prePushTimeout = testing.prePushTimeout || 30;
  const languages = [...new Set((plan.stacks || []).map(s => s.language))];
  const hasSuppressionGate = preCommit.some(h => h.tool === 'suppression');
  const patterns = hasSuppressionGate ? blockedPatterns(plan, config) : [];

  lines.push(BEGIN_MARK);
  lines.push('<!-- Managed by devflow. Regenerated by `devflow init` / `devflow update`. Edits inside this block are overwritten. -->');
  lines.push('## devflow — enforced quality gates');
  lines.push('');
  lines.push('This repository is enforced by devflow. Commits and pushes are gated by machine. Treat every rule below as a hard constraint, not a preference.');
  if (languages.length > 0) {
    lines.push('');
    lines.push(`Detected stack: ${languages.join(', ')}.`);
  }

  // ---- Workflow ----
  lines.push('');
  lines.push('### Before every commit');
  lines.push('');
  lines.push('1. Run `devflow check --pre-commit` and fix every `✗`. The pre-commit hook runs the same checks and rejects the commit otherwise.');
  lines.push('2. After a failure, read `.devflow/findings.json`. Each finding carries `file`, `line`, `description` and `fixSteps`. Fix the cause named there.');
  lines.push('3. If a blocking finding cannot be fixed, run `devflow override --rule <hook-id> --reason "<why>"`. Reason must be at least 10 characters; the override expires within 30 days and is logged with your identity. Do not silence the tool in code.');
  lines.push('4. Never run `git commit --no-verify` or `git push --no-verify`.');

  // ---- Pre-commit table ----
  if (preCommit.length > 0) {
    lines.push('');
    lines.push('### Pre-commit gates (staged files)');
    lines.push('');
    lines.push('| Hook id | Tool | On failure |');
    lines.push('|---------|------|------------|');
    for (const h of preCommit) {
      const tool = h.internal ? 'devflow (built in)' : h.command;
      lines.push(`| \`${h.id}\` | ${tool} | ${h.failPolicy === 'closed' ? 'blocks commit' : 'warning only'} |`);
    }
    lines.push('');
    lines.push('Tools not installed locally are skipped at pre-commit and enforced in CI instead. Install them from `.devflow/setup.md`.');
  }

  // ---- Pre-push ----
  if (prePushEnabled) {
    lines.push('');
    lines.push('### Pre-push gate');
    lines.push('');
    for (const j of testJobs) {
      const cmd = [j.command, ...(j.args || [])].join(' ');
      const scope = j.scope && j.scope !== '.' ? ` (in \`${j.scope}\`)` : '';
      lines.push(`- Tests must pass${scope}: \`${cmd}\` — ${prePushTimeout}s timeout. A failing suite blocks the push.`);
    }
  }

  // ---- CI ----
  if (ciJobs.length > 0) {
    lines.push('');
    lines.push('### CI gates (every push)');
    lines.push('');
    lines.push('| Job | On failure |');
    lines.push('|-----|------------|');
    for (const j of ciJobs) {
      lines.push(`| ${j.name || j.id} (\`${j.id}\`) | ${policyLabel(j.failPolicy)} |`);
    }
    if (plan.mergeGate && Array.isArray(plan.mergeGate.requiredChecks) && plan.mergeGate.requiredChecks.length > 0) {
      lines.push('');
      lines.push(`Required to merge: ${plan.mergeGate.requiredChecks.map(c => '`' + c + '`').join(', ')}.`);
    }
  }

  // ---- PR rules ----
  const prChecks = (plan.prGate && plan.prGate.checks) || [];
  const prLines = [];
  for (const c of prChecks) {
    if (c.type === 'loc_limit' && c.config) {
      prLines.push(`- Keep a PR under ${c.config.max} changed lines${c.config.hotfixMax ? ` (${c.config.hotfixMax} for hotfixes)` : ''}. Split larger work.`);
    } else if (c.type === 'branch_naming' && c.config && Array.isArray(c.config.prefixes)) {
      prLines.push(`- Branch names start with one of: ${c.config.prefixes.map(p => '`' + p + '`').join(', ')}.`);
    } else if (c.type === 'branch_age' && c.config) {
      const parts = Object.entries(c.config).map(([k, v]) => `${k} ${v}h`);
      prLines.push(`- Branch age limits: ${parts.join(', ')}. Merge or close before then.`);
    }
  }
  if (prLines.length > 0) {
    lines.push('');
    lines.push('### Pull request rules');
    lines.push('');
    lines.push(...prLines);
  }

  // ---- Do not ----
  lines.push('');
  lines.push('### Do not');
  lines.push('');
  if (patterns.length > 0) {
    lines.push('- Do not add suppression comments or test skips to make a check pass. New occurrences of these are blocked at pre-commit for this stack:');
    for (const p of patterns) {
      const token = PATTERN_TOKEN[p.id] || p.id;
      lines.push(`  - \`${token}\` — ${p.description}`);
    }
    lines.push('  Fix the underlying issue. If a suppression is required, use `devflow override --rule suppression-gate --reason "..."`.');
  }
  lines.push('- Do not commit secrets, tokens, private keys or `.env` files. Read secrets from environment variables. The secrets scan blocks the commit and the value is already compromised once committed.');
  lines.push('- Do not edit, disable or delete `.git/hooks/pre-commit`, `.git/hooks/pre-push`, anything under `.devflow/`, or the generated CI workflow files.');
  lines.push('- Do not delete or skip tests, lower coverage thresholds, or change lint/format configuration to get a green run.');
  lines.push('- Do not remove or weaken this block. It is regenerated from `.devflow/config.yml`; change the config instead.');
  lines.push(END_MARK);

  return lines.join('\n') + '\n';
}

/**
 * Insert or replace the managed block in a file's content.
 */
function applyBlock(existing, block) {
  const begin = existing.indexOf(BEGIN_MARK);
  const end = existing.indexOf(END_MARK);
  if (begin !== -1 && end !== -1 && end > begin) {
    const after = end + END_MARK.length;
    // Block includes its own trailing newline; drop the one that followed the old END_MARK
    const tail = existing.slice(after).replace(/^\n/, '');
    return existing.slice(0, begin) + block + tail;
  }
  if (existing.length === 0) return block;
  const sep = existing.endsWith('\n\n') ? '' : existing.endsWith('\n') ? '\n' : '\n\n';
  return existing + sep + block;
}

/**
 * Write the managed block into the repo's agent instruction file(s).
 *
 * @param {string} repoRoot
 * @param {Object} plan
 * @param {Object} [config]
 * @returns {{ enabled: boolean, written: Array<{path: string, created: boolean}>, files: string[] }}
 */
function writeAgentInstructions(repoRoot, plan, config = {}) {
  const { enabled, files } = resolveOptions(config);
  if (!enabled) return { enabled: false, written: [], files };

  const block = buildAgentInstructions(plan, config);
  const existing = files.filter(f => fs.existsSync(path.join(repoRoot, f)));
  const targets = existing.length > 0 ? existing : files;
  const written = [];

  for (const rel of targets) {
    const abs = path.join(repoRoot, rel);
    const created = !fs.existsSync(abs);
    const current = created ? '' : fs.readFileSync(abs, 'utf8');
    const next = applyBlock(current, block);
    if (created || next !== current) {
      fs.writeFileSync(abs, next);
    }
    written.push({ path: rel, created, changed: created || next !== current });
  }

  return { enabled: true, written, files };
}

module.exports = {
  BEGIN_MARK,
  END_MARK,
  DEFAULT_FILES,
  buildAgentInstructions,
  writeAgentInstructions,
  applyBlock,
  resolveOptions,
};
