/**
 * devflow Config Reader
 *
 * Reads and validates .devflow/config.yml from a repository.
 * Falls back to sensible defaults when no config exists.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const CONFIG_DIR = '.devflow';
const CONFIG_FILE = 'config.yml';

/**
 * Parse a simple YAML-like config file.
 * Handles the subset of YAML used by devflow config — no external dependency.
 * Supports: key: value, lists (- item), nested objects (indentation).
 *
 * For full YAML parsing, this would use js-yaml. Keeping it zero-dep for now.
 * Complex configs will need a proper parser — this handles the bootstrap case.
 *
 * @param {string} content - File content
 * @returns {Object}
 */
function parseSimpleYaml(content) {
  const result = {};
  const lines = content.split('\n');
  let currentKey = null;
  let currentList = null;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    // List item
    if (trimmed.startsWith('- ')) {
      if (currentList) {
        const value = trimmed.slice(2).trim();
        // Handle "key: value" within list items
        if (value.includes(': ')) {
          const [k, ...rest] = value.split(': ');
          const obj = {};
          obj[k.trim()] = rest.join(': ').trim();
          currentList.push(obj);
        } else {
          currentList.push(value);
        }
      }
      continue;
    }

    // Key: value pair
    const colonIdx = trimmed.indexOf(':');
    if (colonIdx > 0) {
      const key = trimmed.slice(0, colonIdx).trim();
      const value = trimmed.slice(colonIdx + 1).trim();

      if (value === '' || value === '|') {
        // Start of a list or nested object
        result[key] = [];
        currentKey = key;
        currentList = result[key];
      } else {
        result[key] = parseValue(value);
        currentKey = null;
        currentList = null;
      }
    }
  }

  return result;
}

function parseValue(str) {
  if (str === 'true') return true;
  if (str === 'false') return false;
  if (str === 'null') return null;
  if (/^\d+$/.test(str)) return parseInt(str, 10);
  // Strip quotes
  if ((str.startsWith('"') && str.endsWith('"')) || (str.startsWith("'") && str.endsWith("'"))) {
    return str.slice(1, -1);
  }
  // Strip square brackets for inline arrays
  if (str.startsWith('[') && str.endsWith(']')) {
    return str.slice(1, -1).split(',').map(s => parseValue(s.trim()));
  }
  return str;
}

/**
 * Read devflow config from a repository.
 *
 * @param {string} repoRoot - Absolute path to repository root
 * @returns {Object} Parsed config merged with defaults
 */
function readConfig(repoRoot) {
  const configPath = path.join(repoRoot, CONFIG_DIR, CONFIG_FILE);

  const defaults = {
    platform: null,
    modules: [],
    failPolicy: {},
    prChecks: [],
    preCommitMaxDuration: 15000,
    requireAllGreen: true,
    auditTiers: [1, 2],
    auditLogPath: '.devflow/audit.log',
    discord: null,
    email: null,
    prComment: true,
    licencePolicy: null,
  };

  if (!fs.existsSync(configPath)) {
    return defaults;
  }

  try {
    const content = fs.readFileSync(configPath, 'utf8');
    const parsed = parseSimpleYaml(content);
    return { ...defaults, ...parsed };
  } catch (err) {
    console.error(`Warning: Could not parse ${configPath}: ${err.message}`);
    return defaults;
  }
}

/**
 * Ensure .devflow directory exists.
 *
 * @param {string} repoRoot
 */
function ensureConfigDir(repoRoot) {
  const configDir = path.join(repoRoot, CONFIG_DIR);
  if (!fs.existsSync(configDir)) {
    fs.mkdirSync(configDir, { recursive: true });
  }
}

/**
 * Write a default config file to .devflow/config.yml.
 *
 * @param {string} repoRoot
 * @param {Object} config
 */
function writeConfig(repoRoot, config) {
  ensureConfigDir(repoRoot);
  const configPath = path.join(repoRoot, CONFIG_DIR, CONFIG_FILE);

  const lines = [
    '# devflow configuration',
    '# Generated by devflow init — edit as needed',
    '',
  ];

  if (config.platform) {
    lines.push(`platform: ${config.platform}`);
  }

  if (config.stacks && config.stacks.length > 0) {
    lines.push('', 'stack:');
    for (const stack of config.stacks) {
      lines.push(`  - language: ${stack.language}`);
      lines.push(`    path: ${stack.path}`);
    }
  }

  if (config.modules && config.modules.length > 0) {
    lines.push('', 'modules:');
    for (const mod of config.modules) {
      lines.push(`  - ${mod}`);
    }
  }

  lines.push('', 'severity:');
  lines.push('  cve_block: [critical, high]');
  lines.push('  cve_warn: [medium]');

  lines.push('');
  fs.writeFileSync(configPath, lines.join('\n') + '\n');
}

module.exports = {
  readConfig,
  writeConfig,
  ensureConfigDir,
  parseSimpleYaml,
  CONFIG_DIR,
  CONFIG_FILE,
};
